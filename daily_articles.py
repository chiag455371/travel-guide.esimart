def get_article_data(slug):
    if slug in ARTICLE_CONTENT:
        return ARTICLE_CONTENT[slug], slug
    elif slug in ARTICLE_TEMPLATES:
        title, region, city = ARTICLE_TEMPLATES[slug]
        data = generate_fallback_content(region, city)
        data['title'] = title
        return data, slug
    else:
        region = 'jp' if slug.startswith('jp') else 'kr' if slug.startswith('kr') else 'tw' if slug.startswith('tw') else 'eu' if slug.startswith('eu') else 'oce'
        city = slug.replace('_',' ').title()
        data = generate_fallback_content(region, city)
        data['title'] = f'{city}旅遊全攻略：{REGION_NAME.get(region,"該地區")}必訪景點與美食推薦'
        return data, slug

